func glyph(code byte, cg []byte) [8]byte {
	var g [8]byte
	if code < 16 {
		copy(g[:], cg[int(code&7)*8:int(code&7)*8+8])
		return g
	}
	s, ok := font[code]
	if !ok {
		s = font['?']
	}
	for i, r := range strings.Split(s, ",") {
		v, _ := strconv.ParseUint(r, 2, 8)
		g[i] = byte(v)
	}
	return g
}

func main() {
	out := flag.String("o", "screens", "output directory")
	scale := flag.Int("scale", 4, "pixels per LCD dot")
	flag.Parse()
	if err := os.MkdirAll(*out, 0o755); err != nil {
		fail(err)
	}
	bezel, glass := color.RGBA{22, 25, 15, 255}, color.RGBA{159, 178, 31, 255}
	off, on := color.RGBA{148, 166, 27, 255}, color.RGBA{34, 44, 12, 255}
	in := bufio.NewScanner(os.Stdin)
	in.Buffer(make([]byte, 1<<20), 1<<20)
	for in.Scan() {
		f := strings.Fields(in.Text())
		if len(f) < 3 {
			continue
		}
		cols, _ := strconv.Atoi(f[1])
		rows, _ := strconv.Atoi(f[2])
		if len(f) != 3+cols*rows+64 {
			fail(fmt.Errorf("%s: bad line", f[0]))
		}
		b := make([]byte, len(f)-3)
		for i, h := range f[3:] {
			v, _ := strconv.ParseUint(h, 16, 8)
			b[i] = byte(v)
		}
		cells, cg := b[:cols*rows], b[cols*rows:]
		sc, pad, border := *scale, 4**scale, 2
		W, H := (cols*6-1+2*border)*sc+2*pad, (rows*9-1+2*border)*sc+2*pad
		img := image.NewRGBA(image.Rect(0, 0, W, H))
		for y := 0; y < H; y++ {
			for x := 0; x < W; x++ {
				c := bezel
				if x >= pad && x < W-pad && y >= pad && y < H-pad {
					c = glass
				}
				img.SetRGBA(x, y, c)
			}
		}
		for r := 0; r < rows; r++ {
			for c := 0; c < cols; c++ {
				g := glyph(cells[r*cols+c], cg)
				for dy := 0; dy < 8; dy++ {
					for dx := 0; dx < 5; dx++ {
						col := off
						if g[dy]>>(4-dx)&1 == 1 {
							col = on
						}
						px, py := pad+(border+c*6+dx)*sc, pad+(border+r*9+dy)*sc
						for yy := 0; yy < sc-1; yy++ {
							for xx := 0; xx < sc-1; xx++ {
								img.SetRGBA(px+xx, py+yy, col)
							}
						}
					}
				}
			}
		}
		name := filepath.Join(*out, f[0]+".png")
		w, err := os.Create(name)
		if err != nil {
			fail(err)
		}
		if err := png.Encode(w, img); err != nil {
			fail(err)
		}
		w.Close()
		fmt.Fprintln(os.Stderr, name)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "preview:", err)
	os.Exit(1)
}
